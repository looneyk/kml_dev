//------------------------------------------------------------------------------
// Position.cpp
//------------------------------------------------------------------------------

#include "Position.hpp"

//------------------------------------------------------------------------------
quetzal::roguelike::Position::Position() :
    m_x(0.f),
    m_y(0.f),
    m_z(0.f)
{
}

//------------------------------------------------------------------------------
quetzal::roguelike::Position::Position(float x, float y, float z) :
    m_x(x),
    m_y(y),
    m_z(z)
{
}

//------------------------------------------------------------------------------
float quetzal::roguelike::Position::x()
{
    return m_x;
}

//------------------------------------------------------------------------------
float quetzal::roguelike::Position::y()
{
    return m_y;
}

//------------------------------------------------------------------------------
float quetzal::roguelike::Position::z()
{
    return m_z;
}

//------------------------------------------------------------------------------
void quetzal::roguelike::Position::set(float x, float y, float z)
{
    m_x = x;
    m_y = y;
    m_z = z;
    return;
}
