//------------------------------------------------------------------------------
// Size.cpp
//------------------------------------------------------------------------------

#include "Size.hpp"

//------------------------------------------------------------------------------
quetzal::hex_level::Size::Size() :
    m_dx(0.f),
    m_dy(0.f),
    m_dz(0.f)
{
}

//------------------------------------------------------------------------------
quetzal::hex_level::Size::Size(float dx, float dy, float dz) :
    m_dx(dx),
    m_dy(dy),
    m_dz(dz)
{
}

//------------------------------------------------------------------------------
float quetzal::hex_level::Size::dx()
{
    return m_dx;
}

//------------------------------------------------------------------------------
float quetzal::hex_level::Size::dy()
{
    return m_dy;
}

//------------------------------------------------------------------------------
float quetzal::hex_level::Size::dz()
{
    return m_dz;
}

//------------------------------------------------------------------------------
void quetzal::hex_level::Size::set(float dx, float dy, float dz)
{
    m_dx = dx;
    m_dy = dy;
    m_dz = dz;
    return;
}
